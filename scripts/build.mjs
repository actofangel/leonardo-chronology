#!/usr/bin/env node
// Build the published site from data/.
//
//   node scripts/build.mjs                    default view (no scenario)
//   node scripts/build.mjs --scenario hyp-x   view under a working hypothesis
//   node scripts/build.mjs --out dist         output folder (default dist)
//
// Output:
//   index.html        entity browser (database home)
//   chronology.html   the chronology view, records injected into the page
//   db.json           every entity, with resolved claims and backlinks
//   reviews.json      review layer for the chronology page
//   extra.json        empty; new records now go in data/
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { ROOT, loadAll, loadView, loadVocab, resolve, LANES, LANE_CONST, isAdmitted } from './lib.mjs';

const arg = (name, dflt) => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : dflt; };
const OUT = path.resolve(ROOT, arg('--out', 'dist'));
const SCENARIO = arg('--scenario', null);

const { entities, files, problems } = loadAll();
if (problems.length) { problems.forEach((p) => console.error('error: ' + p)); process.exit(1); }

// ---------- scenario ----------
let forced = new Set();
let scenario = null;
if (SCENARIO) {
  scenario = entities.get(SCENARIO);
  if (!scenario || scenario.type !== 'hypothesis') { console.error(`error: --scenario ${SCENARIO} is not a hypothesis entity`); process.exit(1); }
  forced = new Set(scenario.assumes || []);
}

// ---------- backlinks and resolution ----------
const backlinks = {};
for (const e of entities.values()) {
  for (const r of e.relations || []) (backlinks[r.target] = backlinks[r.target] || []).push({ from: e.id, rel: r.rel });
  for (const c of e.claims || []) for (const s of c.sources || []) if (s.ref) (backlinks[s.ref] = backlinks[s.ref] || []).push({ from: e.id, rel: 'cited_by', claim: c.id });
}
const db = { schema: 'ldv-db/1', built: new Date().toISOString().slice(0, 10), scenario: SCENARIO, entities: {} };
const stats = { entities: 0, claims: 0, verified: 0, admittedSourced: 0, byType: {} };
for (const e of entities.values()) {
  const resolved = resolve(e, entities, forced);
  db.entities[e.id] = Object.assign({}, e, { _file: files.get(e.id), _resolved: resolved, _backlinks: backlinks[e.id] || [] });
  stats.entities++; stats.byType[e.type] = (stats.byType[e.type] || 0) + 1;
  for (const c of e.claims || []) { stats.claims++; if (c.status === 'verified') stats.verified++; if (isAdmitted(c, entities)) stats.admittedSourced++; }
}
db.stats = stats;
db.vocab = loadVocab().axes;
const facets = {};
for (const e of entities.values()) for (const [axis, val] of Object.entries(e.classification || {})) {
  for (const v of (Array.isArray(val) ? val : [val])) { facets[axis] = facets[axis] || {}; facets[axis][v] = (facets[axis][v] || 0) + 1; }
}
db.facets = facets;

// ---------- chronology records ----------
const lanes = Object.fromEntries(LANES.map((l) => [l, []]));
const reviews = {};
for (const e of entities.values()) {
  if (!e.timeline) continue;
  const t = e.timeline;
  const rec = { id: e.id, title: e.label, kind: t.kind, start: t.start };
  if (t.end !== undefined) rec.end = t.end;
  Object.assign(rec, { date: t.date, tier: t.tier, place: t.place, text: t.text, basis: t.basis });
  // Under a scenario, a forced timeline or date claim with numeric start replaces the display dates.
  if (SCENARIO) {
    for (const about of ['timeline', 'date']) {
      const r = db.entities[e.id]._resolved[about];
      if (r && r.forced) {
        const c = e.claims.find((x) => x.id === r.claim);
        if (c && c.value && typeof c.value.start === 'number') {
          rec.start = c.value.start; if (c.value.end !== undefined) rec.end = c.value.end; else delete rec.end;
          if (c.value.text) rec.date = c.value.text;
          rec.text = `[Scenario ${SCENARIO}] ` + rec.text;
        }
      }
    }
  }
  lanes[t.lane].push(rec);
  if (e.review) reviews[e.id] = e.review;
}
for (const l of LANES) lanes[l].sort((a, b) => a.start - b.start || a.id.localeCompare(b.id));
const view = loadView();
let data = `/* Generated by scripts/build.mjs from data/. Do not edit here. */\nconst ERAS = ${JSON.stringify(view.eras)};\n`;
for (const l of LANES) data += `const ${LANE_CONST[l]} = ${JSON.stringify(lanes[l])};\n`;
const updated = [...entities.values()].flatMap((e) => (e.review?.history || []).map((h) => h.at)).sort().pop() || db.built;
const reviewsFile = { schema: 'ldv-chronology-reviews/1', updated, reviews };

let page = readFileSync(path.join(ROOT, 'site', 'chronology.html'), 'utf8');
if (!page.includes('/*@@DATA@@*/')) { console.error('error: site/chronology.html has no data placeholder'); process.exit(1); }
page = page.replace('/*@@DATA@@*/', () => data);
if (SCENARIO) page = page.replace('<h1>Leonardo Chronology</h1>', () => `<h1>Leonardo Chronology</h1>\n    <p class="status"><b>Scenario view: ${scenario.label}.</b> This build applies the claims assumed by a working hypothesis. It is not the default reading of the evidence.</p>`);

mkdirSync(OUT, { recursive: true });
writeFileSync(path.join(OUT, 'chronology.html'), page);
writeFileSync(path.join(OUT, 'reviews.json'), JSON.stringify(reviewsFile, null, 2) + '\n');
writeFileSync(path.join(OUT, 'extra.json'), JSON.stringify({ schema: 'ldv-chronology-extra/1', records: [] }, null, 2) + '\n');
writeFileSync(path.join(OUT, 'db.json'), JSON.stringify(db) + '\n');
if (existsSync(path.join(ROOT, 'site', 'explorer.html'))) copyFileSync(path.join(ROOT, 'site', 'explorer.html'), path.join(OUT, 'index.html'));
writeFileSync(path.join(OUT, '.nojekyll'), '');

const n = LANES.reduce((s, l) => s + lanes[l].length, 0);
console.log(`Built ${OUT}${SCENARIO ? ' (scenario ' + SCENARIO + ')' : ''}: ${stats.entities} entities, ${stats.claims} claims (${stats.verified} verified, ${stats.admittedSourced} with an admitted source), ${n} chronology records.`);
console.log('By type: ' + Object.entries(stats.byType).map(([k, v]) => `${k} ${v}`).join(', '));
